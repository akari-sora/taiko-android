#!/usr/bin/env python3
"""Assemble a pinned public NSO and generate canonical runtime authority.

Source identity changes require reviewing/updating android_profiles.py pins.
Normal generation never learns authority from its newly built package.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile

from android_import import import_module
import android_profiles as profiles
from gen_android_fixtures import toolchain

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'dm/platform/android/observation_fixtures'


def assemble(tools):
    clang, objcopy = tools
    suffix = '.exe' if clang.suffix == '.exe' else ''
    nm = clang.parent / ('llvm-nm' + suffix)
    with tempfile.TemporaryDirectory(prefix='dm-observation-') as temporary:
        elf, binary = Path(temporary) / 'fixture.elf', Path(temporary) / 'fixture.bin'
        subprocess.run([str(clang), '--target=aarch64-linux-android29', '-nostdlib', '-static',
                        '-Wl,-T,' + str(FIXTURES / 'fixture.ld'), '-Wl,--build-id=none',
                        str(FIXTURES / 'main.S'), '-o', str(elf)], check=True, capture_output=True)
        subprocess.run([str(objcopy), '-O', 'binary', '--only-section=.text', str(elf), str(binary)],
                       check=True, capture_output=True)
        listing = subprocess.run([str(nm), '-S', '--defined-only', '--format=posix', str(elf)],
                                 check=True, capture_output=True, text=True).stdout
        functions = {}
        for line in listing.splitlines():
            fields = line.split()
            if len(fields) == 4 and fields[1] == 'T':
                functions[fields[0]] = (int(fields[2], 16), int(fields[3], 16))
        return binary.read_bytes(), functions


def make_nso(text, functions):
    """Independent minimal NSO0/ELF64 metadata, no import/provider shortcuts."""
    ro, data = bytearray(4096), bytearray(4096)
    records, strings = [bytes(24)], bytearray(b'\0')
    for name, (offset, size) in sorted(functions.items()):
        name_offset = len(strings)
        strings += name.encode('ascii') + b'\0'
        records.append(struct.pack('<IBBHQQ', name_offset, 0x12, 0, 1, offset, size))
    symbols = b''.join(records)
    ro[:len(symbols)] = symbols
    ro[len(symbols):len(symbols) + len(strings)] = strings
    hash_offset = (len(symbols) + len(strings) + 7) & -8
    words = [1, len(records), 1, 0] + [i + 1 if i + 1 < len(records) else 0 for i in range(1, len(records))]
    ro[hash_offset:hash_offset + len(words) * 4] = struct.pack('<' + 'I' * len(words), *words)
    # Actual unaligned RO strings, including a string terminating at the last
    # readable byte. The UI bus must not scan segment-alignment holes.
    message = b'FrontEndNavigation\0ToGame\0FixturePanel\0'
    ro[0x601:0x601 + len(message)] = message
    tail = b'FixtureTail\0'
    ro[-len(tail):] = tail
    assert len(ro) == 4096
    dynamic = [(5, 0x4000 + len(symbols)), (10, len(strings)), (6, 0x4000),
               (11, 24), (4, 0x4000 + hash_offset), (12, functions['fixture_init'][0]), (0, 0)]
    for index, (tag, value) in enumerate(dynamic):
        struct.pack_into('<qQ', data, 0x400 + index * 16, tag, value)
    header = bytearray(256)
    header[:4] = b'NSO0'
    struct.pack_into('<I', header, 12, 0x38)
    header[0x40:0x60] = hashlib.sha256(b'dm-observation-fixture-v1' + text + ro + data).digest()
    struct.pack_into('<IIII', header, 0x90, len(symbols), len(strings), 0, len(symbols))
    parts, cursor = [], 256
    for index, (raw, memory) in enumerate(((text, 0), (bytes(ro), 0x4000), (bytes(data), 0x8000))):
        struct.pack_into('<IIII', header, 0x10 + index * 16, cursor, memory, len(raw), 4096 if index == 2 else 0)
        struct.pack_into('<I', header, 0x60 + index * 4, len(raw))
        header[0xA0 + index * 32:0xC0 + index * 32] = hashlib.sha256(raw).digest()
        parts.append(raw)
        cursor += len(raw)
    return bytes(header) + b''.join(parts)


def hex_array(data):
    return '{{' + ','.join(f'0x{x:02x}' for x in data) + '}}'


def catalog():
    lines = ['// Generated by gen_android_observations.py from android_profiles.py.',
             '// Included inside namespace dm_android; synthetic entries grant no game capabilities.']
    for index, profile in enumerate(profiles.PROFILES):
        lines.append(f'static const ObservationRecord profile_{index}_observations[] = {{')
        lines += [f'    {{{p.offset}u,{p.id}u,0x{p.word:08x}u}},' for p in profile.observations]
        lines.append('};')
        lines.append(f'static const ParameterRecord profile_{index}_parameters[] = {{')
        lines += [f'    {{{p.a}u,{p.b}u,0x{p.word_a:08x}u,0x{p.word_b:08x}u,{p.destination}u,{p.slot}u,{p.flags}u}},' for p in profile.parameters]
        lines.append('};')
    lines.append('const ObservationProfile kObservationProfiles[] = {')
    for index, profile in enumerate(profiles.PROFILES):
        strings = ','.join(json.dumps(x) for x in (profile.target, profile.module, profile.variant, profile.ruleset))
        lines.append(f'    {{{strings},{hex_array(profile.build_id)},{hex_array(profile.source_sha256)},{hex_array(profile.digest)},'
                     f'{profile.identity_class}u,profile_{index}_observations,{len(profile.observations)}u,'
                     f'profile_{index}_parameters,{len(profile.parameters)}u}},')
    lines += ['};', 'const size_t kObservationProfileCount = sizeof(kObservationProfiles)/sizeof(kObservationProfiles[0]);', '']
    return '\n'.join(lines).encode()


def generate(tools):
    source = make_nso(*assemble(tools))
    package, report = import_module(source, 'main', package_version=2, profile='synthetic-observation-v1')
    lines = ['// Generated public NSO, production importer, explicit wire v2.', '#pragma once',
             '#include <stdint.h>', '#include <stddef.h>', 'alignas(8) static const uint8_t dm_observation_main_bytes[] = {']
    for offset in range(0, len(package), 24):
        lines.append('    ' + ','.join(f'0x{x:02x}' for x in package[offset:offset + 24]) + ',')
    lines += ['};', 'static constexpr size_t dm_observation_main_size = sizeof(dm_observation_main_bytes);',
              'static const uint8_t dm_observation_main_package_sha256[32] = ' + hex_array(hashlib.sha256(package).digest())[1:-1] + ';', '']
    return {'main.nso': source, 'main.dmag': package, 'generated_observations.h': '\n'.join(lines).encode(),
            'generated_catalog.inc': catalog(), 'import.json': (json.dumps(report, indent=2) + '\n').encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ndk')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--print-identity', action='store_true')
    args = parser.parse_args()
    tools = toolchain(args.ndk)
    if args.print_identity:
        source = make_nso(*assemble(tools))
        print('build_id=' + source[0x40:0x60].hex())
        print('source_sha256=' + hashlib.sha256(source).hexdigest())
        return
    for name, content in generate(tools).items():
        target = FIXTURES / name
        if args.check:
            if not target.is_file() or target.read_bytes() != content:
                raise SystemExit(f'{target} differs; regenerate after reviewing profile/source identity')
        else:
            target.write_bytes(content)
    print(('Verified' if args.check else 'Generated') + ' independently pinned observation NSO/catalog via production wire-v2 importer; game boot NOT_RUN')


if __name__ == '__main__':
    main()
