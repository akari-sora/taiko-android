#!/usr/bin/env python3
"""Assemble self-authored native exclusive-monitor contract fixtures."""
import argparse
from pathlib import Path

from android_rewrite import rewrite
from gen_android_fixtures import assemble, toolchain

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'dm/platform/android/exclusive_fixtures'
NAMES = ('counter', 'status', 'live_lr', 'abandon', 'preserve', 'widths',
         'cbnz_retry', 'inverted_retry')


def generate(tools):
    lines = ['// Generated by dm/tools/gen_android_exclusive_fixtures.py; do not edit.',
             '#pragma once', '#include "../guest_abi.h"', '']
    for name in NAMES:
        image = rewrite(assemble(FIXTURES / (name + '.S'), tools))
        prefix = 'dm_fixture_exclusive_' + name
        lines += [f'alignas(8) static const uint8_t {prefix}_bytes[] = {{']
        lines += ['    ' + ', '.join(f'0x{x:02x}' for x in image.bytes[offset:offset + 16]) + ','
                  for offset in range(0, len(image.bytes), 16)]
        lines += ['};', f'static const DmGuestFixup {prefix}_fixups[] = {{']
        lines += [f'    {{{fixup.offset}, {fixup.helper}}},' for fixup in image.fixups]
        lines += ['};', f'static const DmGuestImage {prefix} = {{',
                  f'    DM_ANDROID_GUEST_ABI, {prefix}_bytes, sizeof({prefix}_bytes), {image.entry_offset},',
                  f'    {prefix}_fixups, {len(image.fixups)}, nullptr, 0', '};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ndk')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(toolchain(args.ndk))
    output = FIXTURES / 'fixtures.h'
    if args.check:
        if not output.is_file() or output.read_text(encoding='utf-8') != result:
            raise SystemExit('exclusive fixtures.h differs; regenerate gen_android_exclusive_fixtures.py')
        print(f'exclusive fixtures.h matches {len(NAMES)} assembled and rewritten sources')
    else:
        output.write_text(result, encoding='utf-8', newline='\n')
        print(f'Generated {len(NAMES)} exclusive fixtures')


if __name__ == '__main__':
    main()
