#!/usr/bin/env python3
"""Deterministically assemble self-authored Android fixtures and emit ABI images."""
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

from android_rewrite import rewrite

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'dm/platform/android/fixtures'
NAMES = ('x18_arithmetic', 'x18_memory', 'x18_conditional', 'tls', 'live_lr', 'svc', 'timer',
         'sp_memory', 'sp_preserve')


def toolchain(explicit=None):
    if explicit:
        candidates = [Path(explicit)]
    elif os.environ.get('ANDROID_NDK_HOME'):
        candidates = [Path(os.environ['ANDROID_NDK_HOME'])]
    else:
        sdk = Path(os.environ.get('ANDROID_HOME', str(Path.home() / 'AppData/Local/Android/Sdk')))
        ndks = sdk / 'ndk'
        candidates = sorted(ndks.glob('*'), key=lambda p: tuple(int(x) for x in p.name.split('.') if x.isdigit()), reverse=True)
        # The repository's pinned build toolchain is preferred when installed.
        pinned = ndks / '28.2.13676358'
        if pinned in candidates:
            candidates.remove(pinned)
            candidates.insert(0, pinned)
    for ndk in candidates:
        for host in ('windows-x86_64', 'linux-x86_64', 'darwin-x86_64'):
            suffix = '.exe' if host.startswith('windows') else ''
            directory = ndk / 'toolchains/llvm/prebuilt' / host / 'bin'
            clang, objcopy = directory / ('clang' + suffix), directory / ('llvm-objcopy' + suffix)
            if clang.is_file() and objcopy.is_file():
                return clang, objcopy
    raise RuntimeError('Installed NDK clang and llvm-objcopy required; pass --ndk PATH')


def assemble(source, tools):
    clang, objcopy = tools
    with tempfile.TemporaryDirectory(prefix='dm-android-fixture-') as temporary:
        elf, binary = Path(temporary) / 'fixture.elf', Path(temporary) / 'fixture.bin'
        # Link at image offset zero so PC-relative relocations are fully resolved;
        # unresolved external references fail instead of producing placeholder bytes.
        subprocess.run([str(clang), '--target=aarch64-linux-android29', '-nostdlib', '-static',
                        '-Wl,-Ttext=0,--entry=fixture,--build-id=none', str(source), '-o', str(elf)],
                       check=True, capture_output=True)
        subprocess.run([str(objcopy), '-O', 'binary', '--only-section=.text', str(elf), str(binary)], check=True, capture_output=True)
        return binary.read_bytes()


def generate(tools):
    lines = ['// Generated by dm/tools/gen_android_fixtures.py; do not hand edit.',
             '// Self-authored raw ARM64 sources pass through the Android ABI v1 emitter.',
             '#pragma once', '#include "../guest_abi.h"', '']
    for name in NAMES:
        image = rewrite(assemble(FIXTURES / (name + '.S'), tools))
        prefix = 'dm_fixture_' + name
        lines += [f'alignas(8) static const uint8_t {prefix}_bytes[] = {{']
        for offset in range(0, len(image.bytes), 16):
            lines.append('    ' + ', '.join(f'0x{x:02x}' for x in image.bytes[offset:offset + 16]) + ',')
        lines += ['};', f'static const DmGuestFixup {prefix}_fixups[] = {{']
        lines += [f'    {{{item.offset}, {item.helper}}},' for item in image.fixups]
        lines += ['};']
        if image.gates:
            lines += [f'static const DmGuestGate {prefix}_gates[] = {{']
            lines += [f'    {{{item.return_offset}, {item.kind}, {item.argument}}},' for item in image.gates]
            lines += ['};']
        lines += [f'static const DmGuestImage {prefix} = {{',
                  f'    DM_ANDROID_GUEST_ABI, {prefix}_bytes, sizeof({prefix}_bytes), {image.entry_offset},',
                  f'    {prefix}_fixups, {len(image.fixups)},',
                  f'    {prefix + "_gates" if image.gates else "nullptr"}, {len(image.gates)}', '};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ndk')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = FIXTURES / 'fixtures.h'
    result = generate(toolchain(args.ndk))
    if args.check:
        if not output.is_file() or output.read_text(encoding='utf-8') != result:
            raise SystemExit('fixtures.h differs; regenerate with gen_android_fixtures.py')
        print(f'fixtures.h matches all {len(NAMES)} assembled and rewritten sources')
    else:
        output.write_text(result, encoding='utf-8', newline='\n')
        print(f'Generated {output}: {len(NAMES)} fixtures')


if __name__ == '__main__':
    main()
