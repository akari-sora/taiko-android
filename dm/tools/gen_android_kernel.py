#!/usr/bin/env python3
"""Assemble the public kernel ABI client and run the production NSO importer."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile

from android_import import import_directory
from gen_android_fixtures import toolchain
from gen_android_modules import make_nso

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'dm/platform/android/kernel_fixtures'
IMPORTS = ('nnsocketSetLastErrno', 'nnsocketGetLastErrno', 'nnsocketSocket')


def assemble(tools):
    clang, objcopy = tools
    suffix = '.exe' if clang.suffix == '.exe' else ''
    with tempfile.TemporaryDirectory(prefix='dm-kernel-asm-') as temporary:
        elf, binary = Path(temporary) / 'fixture.elf', Path(temporary) / 'fixture.bin'
        subprocess.run([str(clang), '--target=aarch64-linux-android29', '-nostdlib', '-static',
                        '-Wl,-T,' + str(ROOT / 'dm/platform/android/module_fixtures/fixture.ld'),
                        '-Wl,--build-id=none', str(FIXTURES / 'kernel.S'), '-o', str(elf)],
                       check=True, capture_output=True)
        subprocess.run([str(objcopy), '-O', 'binary', '--only-section=.text', str(elf), str(binary)],
                       check=True, capture_output=True)
        listing = subprocess.run([str(clang.parent / ('llvm-nm' + suffix)), '-S', '--defined-only',
                                  '--format=posix', str(elf)], check=True, capture_output=True, text=True).stdout
        functions = {}
        for line in listing.splitlines():
            fields = line.split()
            if len(fields) == 4 and fields[1] == 'T':
                functions[fields[0]] = (int(fields[2], 16), int(fields[3], 16), 2)
        return binary.read_bytes(), functions


def make_kernel_nso(text, functions):
    # Reuse the independently exercised NSO segment/header/hash writer. Replace
    # its ELF metadata with this fixture's actual imports; no fixture resolver.
    template = bytearray(make_nso('main', text, functions))
    ro, data = bytearray(4096), bytearray(4096)
    definitions = dict(functions, kernel_results=(0x8100, 0x130, 1))
    records, strings, indices = [bytes(24)], bytearray(b'\0'), {}
    for name in sorted(set(definitions) | set(IMPORTS)):
        indices[name] = len(records)
        offset = len(strings)
        strings += name.encode() + b'\0'
        if name in definitions:
            value, size, kind = definitions[name]
            record = struct.pack('<IBBHQQ', offset, 16 + kind, 0, 1, value, size)
        else:
            record = struct.pack('<IBBHQQ', offset, 18, 0, 0, 0, 0)
        records.append(record)
    symtab = b''.join(records)
    ro[:len(symtab)] = symtab
    ro[len(symtab):len(symtab) + len(strings)] = strings
    string_offset = 0x4000 + len(symtab)
    hash_offset = (string_offset + len(strings) + 7) & -8
    words = [1, len(records), 1, 0] + [i + 1 if i + 1 < len(records) else 0 for i in range(1, len(records))]
    table = struct.pack(f'<{len(words)}I', *words)
    ro[hash_offset - 0x4000:hash_offset - 0x4000 + len(table)] = table
    rela_offset = (hash_offset + len(table) + 7) & -8
    relas = b''.join(struct.pack('<QQq', 0x8000 + i * 8, (indices[name] << 32) | 1026, 0)
                     for i, name in enumerate(IMPORTS))
    ro[rela_offset - 0x4000:rela_offset - 0x4000 + len(relas)] = relas
    dynamic = [(5, string_offset), (10, len(strings)), (6, 0x4000), (11, 24), (4, hash_offset),
               (12, functions['fixture_init'][0]), (23, rela_offset), (2, len(relas)), (20, 7), (0, 0)]
    for i, (tag, value) in enumerate(dynamic):
        struct.pack_into('<qQ', data, 0x400 + i * 16, tag, value)
    struct.pack_into('<IIII', template, 0x90, string_offset - 0x4000, len(strings), 0, len(symtab))
    template[0x40:0x60] = hashlib.sha256(b'kernel' + text + ro + data).digest()
    for i, segment in enumerate((text, ro, data)):
        offset = struct.unpack_from('<I', template, 0x10 + i * 16)[0]
        template[offset:offset + len(segment)] = segment
        template[0xA0 + i * 32:0xC0 + i * 32] = hashlib.sha256(segment).digest()
    return bytes(template)


def generate(tools):
    source = make_kernel_nso(*assemble(tools))
    with tempfile.TemporaryDirectory(prefix='dm-kernel-import-') as temporary:
        exefs, output = Path(temporary) / 'exefs', Path(temporary) / 'prepared'
        exefs.mkdir()
        (exefs / 'main').write_bytes(source)
        report = import_directory(exefs, output, ('main',))
        package = (output / 'main.dmag').read_bytes()
        lines = ['// Generated by dm/tools/gen_android_kernel.py; self-authored NSO through production importer.',
                 '#pragma once', '#include <stddef.h>', '#include <stdint.h>',
                 'alignas(8) static const uint8_t dm_kernel_bytes[] = {']
        for i in range(0, len(package), 24):
            lines.append('    ' + ','.join(f'0x{x:02x}' for x in package[i:i + 24]) + ',')
        lines += ['};', 'static constexpr size_t dm_kernel_size = sizeof(dm_kernel_bytes);',
                  'static const uint8_t dm_kernel_package_sha256[32] = {',
                  '    ' + ','.join(f'0x{x:02x}' for x in hashlib.sha256(package).digest()) + ',', '};', '']
        return {'kernel.nso': source, 'kernel.dmag': package, 'generated_kernel.h': '\n'.join(lines).encode(),
                'import.json': (json.dumps(report, indent=2) + '\n').encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ndk')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generate(toolchain(args.ndk)).items():
        target = FIXTURES / name
        if args.check:
            if not target.is_file() or target.read_bytes() != content:
                raise SystemExit(f'{target} differs; run gen_android_kernel.py')
        else:
            target.write_bytes(content)
    print('Verified kernel NSO production import' if args.check else 'Generated kernel NSO production import')


if __name__ == '__main__':
    main()
